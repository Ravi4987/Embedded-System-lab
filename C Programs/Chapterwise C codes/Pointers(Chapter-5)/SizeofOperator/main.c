/**************************************************Program to find size of various data types using size of Operator******************************************************************/

#include <stdio.h>
#include <stdlib.h>



int main() {
	
	
	
	printf("Size of char type is %d\n",sizeof(char));
	printf("Size of int type is %d\n",sizeof(int));
	printf("Size of float type is %d\n",sizeof(float));
	printf("Size of long type is %d\n",sizeof(long));
	printf("Size of double type is %d\n",sizeof(double));
	
	
	
	
	
	
	return 0;
}
